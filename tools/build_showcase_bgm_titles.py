#!/usr/bin/env python3
"""Generate the reviewed Showcase BGM font exception names from local MasterDB."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build(showcase: Path, music: Path) -> str:
    rows = json.loads(showcase.read_text(encoding="utf-8"))
    music_rows = json.loads(music.read_text(encoding="utf-8"))
    if not isinstance(rows, list) or not isinstance(music_rows, list):
        raise ValueError("Expected raw ShowcaseMusic and Music rows")
    songs = {row["id"]: row for row in music_rows}
    titles = set()
    for row in rows:
        song = songs[row["musicId"]]
        for field in ("name", "description"):
            title = song[field]
            if not isinstance(title, str) or not title or len(title) > 128 or "\0" in title:
                raise ValueError("Invalid BGM title in Music catalog")
            titles.add(title)
    if not titles:
        raise ValueError("Empty ShowcaseMusic catalog; existing font scope retained")
    constants = "\n".join("    U" + json.dumps(title, ensure_ascii=False) + ","
                          for title in sorted(titles))
    return ('// Generated by tools/build_showcase_bgm_titles.py; do not edit by hand.\n'
            '#pragma once\n#include <string_view>\nnamespace mixed_font_router {\n'
            'inline constexpr std::u32string_view showcaseBgmTitles[] = {\n'
            + constants + '\n};\n}\n')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--showcase', type=Path, default=ROOT / '.analysis/master-fetch-full/ShowcaseMusic.json')
    parser.add_argument('--music', type=Path, default=ROOT / '.analysis/master-fetch-full/Music.json')
    parser.add_argument('--output', type=Path, default=ROOT / 'app/src/main/cpp/showcase_bgm_titles.h')
    args = parser.parse_args()
    # Read and validate all input before touching the checked-in snapshot.
    result = build(args.showcase, args.music)
    temporary = args.output.with_suffix(args.output.suffix + '.tmp')
    temporary.write_text(result, encoding='utf-8')
    temporary.replace(args.output)


if __name__ == '__main__':
    main()
